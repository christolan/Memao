package com.xiaojiwei.memao.acceptance;

import android.content.ContentProvider;
import android.content.ContentValues;
import android.database.Cursor;
import android.database.MatrixCursor;
import android.net.Uri;
import android.os.ParcelFileDescriptor;
import android.provider.OpenableColumns;
import java.io.ByteArrayOutputStream;
import java.io.DataOutputStream;
import java.io.FileNotFoundException;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.regex.Pattern;
import java.util.zip.CRC32;
import java.util.zip.DeflaterOutputStream;

/**
 * Test-APK-only provider. Its standalone process has Android/Java classes, but
 * does not inherit the instrumentation target's Kotlin classloader/runtime.
 * It serves generated bytes only and never opens a real filesystem path.
 */
public final class QaMediaProvider extends ContentProvider {
    public static final String AUTHORITY = "com.xiaojiwei.memao.test.qa.media";
    private static final Pattern FIXTURE_PATH = Pattern.compile("/qa-[a-zA-Z0-9-]+\\.png");
    private static final byte[] PNG = buildPng();

    @Override public boolean onCreate() { return true; }

    @Override public String getType(Uri uri) {
        validate(uri);
        return "image/png";
    }

    @Override public Cursor query(Uri uri, String[] projection, String selection, String[] selectionArgs, String sortOrder) {
        validate(uri);
        String[] columns = projection != null ? projection : new String[] {OpenableColumns.DISPLAY_NAME, OpenableColumns.SIZE};
        MatrixCursor cursor = new MatrixCursor(columns);
        Object[] row = new Object[columns.length];
        for (int i = 0; i < columns.length; i++) {
            if (OpenableColumns.DISPLAY_NAME.equals(columns[i])) row[i] = uri.getLastPathSegment();
            else if (OpenableColumns.SIZE.equals(columns[i])) row[i] = PNG.length;
        }
        cursor.addRow(row);
        return cursor;
    }

    @Override public ParcelFileDescriptor openFile(Uri uri, String mode) throws FileNotFoundException {
        validate(uri);
        if (!"r".equals(mode)) throw new FileNotFoundException("Read-only generated fixture");
        final ParcelFileDescriptor[] pipe;
        try { pipe = ParcelFileDescriptor.createPipe(); }
        catch (IOException error) { throw new FileNotFoundException("Cannot create generated fixture pipe"); }
        Thread writer = new Thread(() -> {
            try (ParcelFileDescriptor.AutoCloseOutputStream output = new ParcelFileDescriptor.AutoCloseOutputStream(pipe[1])) {
                output.write(PNG);
            } catch (IOException ignored) {
                // Preview consumers may intentionally close their read end early.
            }
        }, "memao-generated-png");
        writer.setDaemon(true);
        writer.start();
        return pipe[0];
    }

    @Override public Uri insert(Uri uri, ContentValues values) { throw new UnsupportedOperationException("Read-only fixture"); }
    @Override public int delete(Uri uri, String selection, String[] selectionArgs) { throw new UnsupportedOperationException("Read-only fixture"); }
    @Override public int update(Uri uri, ContentValues values, String selection, String[] selectionArgs) { throw new UnsupportedOperationException("Read-only fixture"); }

    private static void validate(Uri uri) {
        String path = uri.getPath();
        if (!AUTHORITY.equals(uri.getAuthority()) || path == null || !FIXTURE_PATH.matcher(path).matches()) {
            throw new IllegalArgumentException("Unknown generated fixture");
        }
    }

    /** Same deterministic generated source for the provider and byte-hash assertion. */
    public static byte[] fixtureBytes() { return PNG.clone(); }

    private static byte[] buildPng() {
        try {
            ByteArrayOutputStream output = new ByteArrayOutputStream();
            DataOutputStream stream = new DataOutputStream(output);
            stream.write(new byte[] {(byte)137, 80, 78, 71, 13, 10, 26, 10});
            ByteArrayOutputStream header = new ByteArrayOutputStream();
            DataOutputStream headerData = new DataOutputStream(header);
            headerData.writeInt(4); headerData.writeInt(3);
            headerData.write(new byte[] {8, 6, 0, 0, 0});
            chunk(stream, "IHDR", header.toByteArray());
            ByteArrayOutputStream compressed = new ByteArrayOutputStream();
            try (DeflaterOutputStream image = new DeflaterOutputStream(compressed)) {
                for (int y = 0; y < 3; y++) {
                    image.write(0);
                    for (int x = 0; x < 4; x++) {
                        image.write(new byte[] {(byte)(40 + x * 32), (byte)(80 + y * 40), 120, (byte)255});
                    }
                }
            }
            chunk(stream, "IDAT", compressed.toByteArray());
            chunk(stream, "IEND", new byte[0]);
            return output.toByteArray();
        } catch (IOException error) { throw new IllegalStateException("Cannot generate PNG fixture", error); }
    }

    private static void chunk(DataOutputStream stream, String type, byte[] data) throws IOException {
        byte[] typeBytes = type.getBytes(StandardCharsets.US_ASCII);
        stream.writeInt(data.length); stream.write(typeBytes); stream.write(data);
        CRC32 crc = new CRC32(); crc.update(typeBytes); crc.update(data);
        stream.writeInt((int)crc.getValue());
    }
}
